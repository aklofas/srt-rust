#!/usr/bin/env bash
# Regenerate tests/coverage/fixture-hashes.toml: a SHA-256 inventory of every
# git-tracked file under each fixture-manifest.toml group root. Run after adding
# or changing any committed fixture/golden, then commit the result.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"
FM="tests/coverage/fixture-manifest.toml"
OUT="tests/coverage/fixture-hashes.toml"

{
  echo "# GENERATED by scripts/gen/fixture-manifest.sh — do not edit by hand."
  echo "# Per-file SHA-256 inventory for every git-tracked file under each"
  echo "# fixture-manifest.toml group root. Enforced by scripts/check/repo/fixture-hashes.sh."
  echo ""
} > "$OUT"

# Roots from the group manifest. Collect every root's tracked files, then
# sort -u BEFORE hashing — nested roots (e.g. codec/av1 under codec) would
# otherwise list the same file twice. git ls-files handles file- and dir-roots.
grep -oE '^root = "[^"]+"' "$FM" | sed -E 's/^root = "(.*)"/\1/' | while IFS= read -r root; do
  git ls-files -- "$root"
done | LC_ALL=C sort -u | while IFS= read -r path; do
  sha="$(sha256sum "$path" | cut -d' ' -f1)"
  printf '[[file]]\npath = "%s"\nsha256 = "%s"\n\n' "$path" "$sha"
done >> "$OUT" || true

echo "wrote $OUT"
